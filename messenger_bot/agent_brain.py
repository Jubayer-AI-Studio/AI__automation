# মেমোরি ক্যাশ (প্রতিটি ইউজারের পূর্বের কথোপকথন মনে রাখার জন্য)
CONVERSATION_HISTORY = {}
MAX_HISTORY_LEN = 6


def call_gemini_api(user_message: str, sender_id: str = "default_user") -> str:
    """গুগল জেমিনি এআই এপিআই কল করে জুবায়ের স্যারের অ্যাসিস্ট্যান্ট হিসেবে উত্তর তৈরি করে।"""
    api_key = os.getenv("GEMINI_API_KEY", "").strip() or GEMINI_API_KEY
    if not api_key:
        # ফলব্যাক উত্তর যদি এপিআই কি এখনও কনফিগার না থাকে
        if any(k in user_message.lower() for k in ["hi", "hello", "সালাম", "hey", "কেমন"]):
            return (
                "আসসালামু আলাইকুম। আমি জুবায়ের স্যারের পার্সোনাল এআই অ্যাসিস্ট্যান্ট। "
                "স্যার এই মুহূর্তে গুরুত্বপূর্ণ সফটওয়্যার ডেভেলপমেন্টের কাজে ব্যস্ত আছেন, "
                "তাই স্যারের হয়ে আমি আপনার সাথে যুক্ত হয়েছি। আপনাকে কীভাবে সহায়তা করতে পারি?"
            )
        elif any(k in user_message.lower() for k in ["কাজ", "প্রজেক্ট", "software", "project", "help"]):
            return (
                "জ্বি অবশ্যই! জুবায়ের স্যার সফটওয়্যার ডেভেলপমেন্ট ও এআই অটোমেশনের কাজ করেন। "
                "আপনার প্রজেক্টের সংক্ষিপ্ত বিবরণ এবং আপনার হোয়াটসঅ্যাপ/ফোন নম্বরটি লিখে রাখুন, "
                "স্যার ফ্রি হওয়ামাত্রই আপনার সাথে সরাসরি যোগাযোগ করবেন।"
            )
        else:
            return (
                "ধন্যবাদ আপনার বার্তার জন্য। আমি জুবায়ের স্যারের এআই অ্যাসিস্ট্যান্ট। "
                "স্যার বর্তমানে কোডিং ল্যাবে ব্যস্ত আছেন। কাজের কোনো নির্দিষ্ট বিষয় থাকলে লিখে রাখুন, "
                "স্যার দেখে দ্রুত উত্তর দেবেন।"
            )

    # ইউজারের মেমোরি লোড
    history = CONVERSATION_HISTORY.get(sender_id, [])

    # Gemini REST API Endpoint (gemini-1.5-flash)
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}

    contents = []
    # পূর্বের হিস্টোরি যোগ করা
    for role, text in history:
        contents.append({"role": role, "parts": [{"text": text}]})

    # বর্তমান মেসেজ
    contents.append({"role": "user", "parts": [{"text": user_message}]})

    payload = {
        "system_instruction": {
            "parts": [{"text": SYSTEM_PROMPT}]
        },
        "contents": contents,
        "generationConfig": {
            "temperature": 0.75,
            "maxOutputTokens": 350
        }
    }

    try:
        res = requests.post(url, headers=headers, json=payload, timeout=15)
        if res.status_code == 200:
            data = res.json()
            reply = data["candidates"][0]["content"]["parts"][0]["text"].strip()

            # হিস্টোরিতে সেভ রাখা
            history.append(("user", user_message))
            history.append(("model", reply))
            CONVERSATION_HISTORY[sender_id] = history[-MAX_HISTORY_LEN:]
            return reply
        else:
            print(f"[Gemini API Error] {res.status_code}: {res.text}")
            return (
                "ধন্যবাদ। আমি জুবায়ের স্যারের এআই অ্যাসিস্ট্যান্ট। স্যার কোডিংয়ে ব্যস্ত আছেন, "
                "কাজের কোনো বার্তা থাকলে দিয়ে রাখুন, স্যার দ্রুত যোগাযোগ করবেন।"
            )
    except Exception as e:
        print(f"[Brain Exception] {e}")
        return (
            "ধন্যবাদ আপনার বার্তার জন্য। আমি জুবায়ের স্যারের এআই সহকারী। "
            "স্যার একটু কাজে ব্যস্ত আছেন, আপনার বার্তাটি সেভ রাখা হয়েছে।"
        )
