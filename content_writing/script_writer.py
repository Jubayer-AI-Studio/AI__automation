def get_reel_content():
    """রোটেশন সিস্টেমে পূর্বে ব্যবহৃত টপিক বাদ দিয়ে সম্পূর্ণ নতুন টপিক নির্বাচন করে।"""
    state = _load_state()
    idx = _pick_fresh(len(CURATED_AI_REELS), state.get("last_reel_indices", []), memory=4)
    state.setdefault("last_reel_indices", []).append(idx)
    state["last_reel_indices"] = state["last_reel_indices"][-8:]
    _save_state(state)

    item = CURATED_AI_REELS[idx].copy()
    sig = "\n\n— Jubayer (AI & Software Developer)"
    if sig not in item["caption"]:
        item["caption"] += sig
    if "#JubayerDev" not in item["hashtags"]:
        item["hashtags"] = item["hashtags"] + ["#JubayerDev"]
    return item


def get_daily_extras():
    """রোটেশন সিস্টেমে পূর্বে ব্যবহৃত পোস্ট, পোল ও কার্ড বাদ দিয়ে নতুনগুলো বেছে নেয়।"""
