import random
import json
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data"
STATE_FILE = DATA_DIR / "rotation_state.json"


def _load_state():
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if STATE_FILE.exists():
        try:
            with open(STATE_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {
        "last_reel_indices": [],
        "last_discussion_indices": [],
        "last_poll_indices": [],
        "last_card_indices": []
    }


def _save_state(state: dict):
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, ensure_ascii=False, indent=2)


def _pick_fresh(pool_size: int, last_used: list, memory: int = 4) -> int:
    avoid = set(last_used[-memory:])
    available = [i for i in range(pool_size) if i not in avoid]
    if not available:
        available = list(range(pool_size))
    return random.choice(available)


